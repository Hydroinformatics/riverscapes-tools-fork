def var_capacity_scatters_conditional(database: str, out_dir: str, var: str,
                                      output: str = "AVG_oCC_EX", std_tolerance=0.5):
    """
    Use standard deviation-based tolerance for each parameter type
    tolerance_std: how many standard deviations away from center
    """
    other_params = [col for col in adjustment_cols if col != var]
    output_name = output.replace("AVG_", "")
    
    # get data
    data = get_results_data(database)
    
    # Get stdev of all adjustment distributions
    stdevs = {}
    with sqlite3.connect(database) as conn:
        cur = conn.cursor()
        cur.execute("SELECT Adjustment, Parameters FROM AdjustmentDistributions")
        results = cur.fetchall()
        for row in results:
            params = row[1].split(", ")
            stdevs[row[0]] = float(params[1])  # stdev is second param for normals
    print(stdevs)
    
    # Define tolerance based on parameter type and its std dev
    param_tolerances = {}
    for param in other_params:
        if 'Scale' in param: # expect: mean=1.0, stdev=0.75
            center = 1.0
            tolerance = std_tolerance * stdevs[param]
        elif 'SPLow' in param and 'Shift' in param: # expect: mean=0, stdev=18.5
            center = 0.0
            tolerance = std_tolerance * stdevs[param]
        elif 'SP2' in param and 'Shift' in param: # expect: mean=0, stdev=200
            center = 0.0
            tolerance = std_tolerance * stdevs[param]
        elif 'Slope' in param and 'Shift' in param: # expect: mean=0, stdev=0.02
            center = 0.0
            tolerance = std_tolerance * stdevs[param]
        
        param_tolerances[param] = (center, tolerance)
    
    # Apply filters
    mask = True
    for param in other_params:
        center, tolerance = param_tolerances[param]
        mask = mask & (abs(data[param] - center) <= tolerance)
    
    filtered_data = data[mask]
    
    print(f"\nConditional Analysis for {var}:")
    print(f"Tolerance: {var} standard deviations")
    print(f"Retained {len(filtered_data)} simulations out of {len(data)} ({100*len(filtered_data)/len(data):.1f}%)")
    
    # Show tolerance values used
    print("Parameter tolerances used:")
    for param, (center, tol) in param_tolerances.items():
        print(f"  {param}: {center:.3f} ± {tol:.3f}")
    
    # seaborn scatter
    sns.regplot(x=filtered_data[var], y=filtered_data[output], marker='o')
    plt.xlabel(var)
    plt.ylabel(f"Mean {output_name} for Input Reaches")
    
    if "oVC" in output:
        plt.title(f"{var} Impact on VEG Capacity (Conditional Scatter)")
    else:
        plt.title(f"{var} Impact on Capacity (Conditional Scatter)")
    
    # add r2 value
    r, p = stats.pearsonr(filtered_data[var], filtered_data[output])
    ax = plt.gca()
    ax.text(.05, .8, 'r={:.2f}, p={:.2g}'.format(r, p),
            transform=ax.transAxes)
    
    if out_dir is not None:
        print(f"...Saving {var} conditional scatter...")
        out_file_path = os.path.join(out_dir, f"scatter-conditional-{var}-{output_name}.png")
        plt.savefig(out_file_path)
        plt.close()
    else:
        plt.show()


def create_tornado_diagram(database: str, output_col='AVG_oCC_EX', method='correlation', 
                         title=None, figsize=(10, 8), out_dir=None):
    """
    Create tornado diagram showing parameter sensitivity for Monte Carlo results.
    Claude AI was used to write much of this function.
    
    Parameters:
    -----------
    database: str
        Path to the Monte Carlo database
    output_col : str
        Name of output column (default: 'oCC_EX')
    method : str
        Sensitivity method: 'correlation', 'regression', or 'standardized'
    title : str
        Custom plot title
    figsize : tuple
        Figure size (width, height)
    save_path : str
        Path to save figure (optional)
    
    Returns:
    --------
    sensitivity_results : dict
        Dictionary with sensitivity metrics and statistics
    """
    
    results_data = get_results_data(database)
        
    # Calculate sensitivity metrics
    sensitivity_metrics = {}
    p_values = {}
    
    for param in adjustment_cols:
        if param not in results_data.columns:
            print(f"Warning: {param} not found in data")
            continue
            
        x = results_data[param].values
        y = results_data[output_col].values
        
        # Remove any NaN values
        mask = ~(np.isnan(x) | np.isnan(y))
        x_clean = x[mask]
        y_clean = y[mask]
        
        if len(x_clean) < 10:  # Need minimum data points
            print(f"Warning: Insufficient data for {param}")
            continue
        
        if method == 'correlation':
            # Pearson correlation coefficient
            corr_coef, p_val = stats.pearsonr(x_clean, y_clean)
            sensitivity_metrics[param] = corr_coef
            p_values[param] = p_val
            
        elif method == 'regression':
            # Standardized regression coefficient
            scaler_x = StandardScaler()
            scaler_y = StandardScaler()
            
            x_std = scaler_x.fit_transform(x_clean.reshape(-1, 1)).flatten()
            y_std = scaler_y.fit_transform(y_clean.reshape(-1, 1)).flatten()
            
            reg = LinearRegression()
            reg.fit(x_std.reshape(-1, 1), y_std)
            sensitivity_metrics[param] = reg.coef_[0]
            
            # Calculate p-value for regression coefficient
            from scipy.stats import t
            n = len(x_clean)
            y_pred = reg.predict(x_std.reshape(-1, 1))
            mse = np.mean((y_std - y_pred) ** 2)
            se = np.sqrt(mse / np.sum((x_std - np.mean(x_std)) ** 2))
            t_stat = reg.coef_[0] / se
            p_val = 2 * (1 - t.cdf(np.abs(t_stat), n - 2))
            p_values[param] = p_val
            
        elif method == 'standardized':
            # Standard deviation-based sensitivity (Morris-like)
            param_range = np.percentile(x_clean, 95) - np.percentile(x_clean, 5)
            output_range = np.percentile(y_clean, 95) - np.percentile(y_clean, 5)
            sensitivity_metrics[param] = output_range / param_range if param_range != 0 else 0
            
            # Use correlation p-value for significance
            _, p_val = stats.pearsonr(x_clean, y_clean)
            p_values[param] = p_val
    
    # Sort parameters by absolute sensitivity
    sorted_params = sorted(sensitivity_metrics.keys(), 
                          key=lambda x: abs(sensitivity_metrics[x]), reverse=False)
    
    # Prepare data for plotting
    param_names = [adjustment_labels[p] for p in sorted_params]
    sensitivities = [sensitivity_metrics[p] for p in sorted_params]
    p_vals = [p_values[p] for p in sorted_params]
    
    # Create tornado plot
    plt.figure(figsize=figsize)
    
    # Color bars by sign and significance
    colors = []
    for i, (sens, p_val) in enumerate(zip(sensitivities, p_vals)):
        if p_val < 0.05:  # Significant
            if sens > 0:
                colors.append('#d62728')  # Red for positive significant
            else:
                colors.append('#2ca02c')  # Green for negative significant
        else:  # Not significant
            if sens > 0:
                colors.append('#ff7f7f')  # Light red for positive non-significant
            else:
                colors.append('#7fbf7f')  # Light green for negative non-significant
    
    # Create horizontal bar chart
    y_pos = np.arange(len(param_names))
    bars = plt.barh(y_pos, sensitivities, color=colors, alpha=0.8, edgecolor='black', linewidth=0.5)
    
    # Customize plot
    plt.yticks(y_pos, param_names, fontsize=11)
    plt.xlabel(f'Sensitivity Index ({method.capitalize()})', fontsize=12, fontweight='bold')
    plt.ylabel('Model Parameters', fontsize=12, fontweight='bold')
    
    if title is None:
        if method == 'correlation':
            title = 'Parameter Sensitivity for Combined Capacity (oCC)\nPearson Correlation Coefficients'
        elif method == 'regression':
            title = 'Parameter Sensitivity for Combined Capacity (oCC)\nStandardized Regression Coefficients'
        else:
            title = 'Parameter Sensitivity for Combined Capacity (oCC)\nStandardized Sensitivity Index'
    
    plt.title(title, fontsize=14, fontweight='bold', pad=20)
    
    # Add vertical line at zero
    plt.axvline(x=0, color='black', linestyle='-', linewidth=0.8)
    
    # Add significance indicators
    for i, (bar, p_val) in enumerate(zip(bars, p_vals)):
        if p_val < 0.001:
            sig_text = '***'
        elif p_val < 0.01:
            sig_text = '**'
        elif p_val < 0.05:
            sig_text = '*'
        else:
            sig_text = 'ns'
        
        # Position text at end of bar
        x_pos = bar.get_width()
        if x_pos >= 0:
            plt.text(x_pos + 0.01 * max(sensitivities), i, sig_text, 
                    va='center', ha='left', fontsize=10, fontweight='bold')
        else:
            plt.text(x_pos - 0.01 * max(abs(np.array(sensitivities))), i, sig_text, 
                    va='center', ha='right', fontsize=10, fontweight='bold')
    
    # Add legend
    from matplotlib.patches import Patch
    legend_elements = [
        Patch(facecolor='#d62728', label='Positive Effect (p < 0.05)'),
        Patch(facecolor='#2ca02c', label='Negative Effect (p < 0.05)'),
        Patch(facecolor='#ff7f7f', label='Positive Effect (p ≥ 0.05)'),
        Patch(facecolor='#7fbf7f', label='Negative Effect (p ≥ 0.05)')
    ]
    plt.legend(handles=legend_elements, fontsize=10)
    
    # Add significance note
    plt.figtext(0.02, 0.02, '* p < 0.05, ** p < 0.01, *** p < 0.001, ns = not significant', 
                fontsize=9, style='italic')
    
    plt.tight_layout()
    plt.grid(axis='x', alpha=0.3)
    
    if out_dir is not None:
        print(f"...Saving tornado plot...")
        out_file_path = os.path.join(out_dir, f"sensitivity-tornado-{method}.png")
        plt.savefig(out_file_path, dpi=600)
        plt.close()
    else:
        plt.show()
    
    # Create summary table
    summary_df = pd.DataFrame({
        'Parameter': [adjustment_labels[p] for p in sorted_params],
        'Sensitivity': sensitivities,
        'P_value': p_vals,
        'Rank': range(1, len(sorted_params) + 1),
        'Significant': ['Yes' if p < 0.05 else 'No' for p in p_vals]
    })
    
    print("\nSensitivity Analysis Summary:")
    print("=" * 60)
    print(summary_df.to_string(index=False, float_format='%.4f'))
    
    # Return results for further analysis
    results = {
        'sensitivity_metrics': sensitivity_metrics,
        'p_values': p_values,
        'summary_table': summary_df,
        'method': method
    }
    
    return results



def calculate_morris_effects(database: str, out_dir: str, percentile=10):
    """
    Calculate Morris elementary effects - changes in output for unit changes in input
    This handles the confounding variable problem naturally
    """
    data = get_results_data(database)
    elementary_effects = {param: [] for param in adjustment_cols}
    
    for param in adjustment_cols:
        # Find pairs of simulations that differ mainly in this parameter
        param_values = data[param].values
        output_values = data["AVG_oCC_EX"].values
        
        # Sort by parameter value
        sort_idx = np.argsort(param_values)
        sorted_param = param_values[sort_idx]
        sorted_output = output_values[sort_idx]
        
        # Calculate finite differences
        for i in range(len(sorted_param) - 1):
            delta_param = sorted_param[i+1] - sorted_param[i]
            delta_output = sorted_output[i+1] - sorted_output[i]
            
            if abs(delta_param) > 1e-6:  # Avoid division by zero
                elementary_effect = delta_output / delta_param
                elementary_effects[param].append(elementary_effect)
    
    # Calculate statistics
    morris_stats = {}
    for param in adjustment_cols:
        effects = elementary_effects[param]
        if effects:
            morris_stats[param] = {
                'mean': np.mean(effects),
                'std': np.std(effects),
                'mean_abs': np.mean(np.abs(effects))
            }
    
    plt_data = pd.DataFrame({
        'Adjustment': [adj for adj in morris_stats.keys()],
        'Absolute Mean': [stats['mean_abs'] for stats in morris_stats.values()],
        'Standard Deviation': [stats['std'] for stats in morris_stats.values()],
    })
    print(plt_data)
    
    # plot Morris mean vs. stddev
    plt.figure(figsize=(8,6))
    sns.scatterplot(data=plt_data, x='Absolute Mean', y='Standard Deviation',
                    s=100, alpha=0.75, hue='Adjustment', style='Adjustment')
    plt.xlabel("Absolute Mean of Elementary Effects")
    plt.ylabel("Standard Deviation of Elementary Effects")
    plt.legend()
    
    if out_dir is not None:
        print(f"...Printing Morris Effects to output dir...")
