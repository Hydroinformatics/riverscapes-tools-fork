def var_distribution(database, var, table, stat='count', num_bins=50, kde_switch=False, title=True, ylabel=True, xlabel=True):
    """
    Generate histograms of the distribution of one variable (input or adjustment).
    :param database: path to a BRAT database (.gpkg)
    :param var: the variable (e.g. iGeo_Slope) to plot a histogram of
    :param stat: seaborn stat kwarg: choose count, frequency, probability, percent, or density
    :param num_bins: number of bins to plot the histogram with
    :param kde_switch: whether or not to plor the kernel density estimate curve on the histogram
    :param title: can disable adding a title to the plot
    :param out_dir: optional path to a folder to save plots to
    """
    
    var_data = select_var(database, var, table)

    # plot raw data
    ax = sns.histplot(data=var_data, bins=num_bins, stat=stat, kde=kde_switch)
    if xlabel:
        plt.xlabel(var)
    if ylabel:
        plt.ylabel(stat.capitalize())
    if title:
        plt.title(f"Distribution of {var} in Siletz Watershed")
        
    print(f"...{num_bins}-bin histogram for {var} generated...")
    return ax

def get_distribution_data(database: str, table: str = "AdjustmentDistributions"):
    """
    Helper function that selects, parses, and returns distributions for Adjustments or Inputs.
        Returns: DataFrame:
            x=Adj/Var   Distribution    Param1  Param2  Param3  Param4
        E.g. for a truncnorm, params:   mu     sigma    left    right
    """
    
    if "Adj" in table:
        xcol = "Adjustment"
        xlabel = adjustment_cols
    elif "Input" in table:
        xcol = "Var"
        xlabel = input_cols
    data = pd.DataFrame(index=xlabel, columns=['Distribution', 'Param1', 'Param2', 'Param3', 'Param4'])
    
    with sqlite3.connect(database) as conn:
        cur = conn.cursor()
        cur.execute(f"SELECT {xcol}, Distribution, Parameters FROM {table}")
        result = cur.fetchall()     # list of tuples, each tuple is a row
        for row in result:
            x, dist, paramstring = row
            paramstring = paramstring.replace("[", "")     # paramstring = [a, b, c, d]
            paramstring = paramstring.replace(" ", "")
            paramstring = paramstring.replace("]", "")
            params = [None, None, None, None]   # if no p3 or p4, will fill None
            for i, val in enumerate(paramstring.split(",")):
                params[i] = float(val)
            data.loc[x] = [dist] + params
    
    # print(data)
    return data

def get_results_data(database: str, table: str = "ResultStats"):
    """
    Helper function that returns adjustments and outputs
        from a table in monte carlo database (e.g. ResultStats) as a DataFrame
    """
    results_cols = ['Veg30_Scale', 'Veg100_Scale', 'SPLow_Scale', 'SPLow_Shift', 
                    'SP2_Scale', 'SP2_Shift', 'Slope_Scale', 'Slope_Shift',
                    'AVG_oVC_EX', 'StDev_oVC_EX', 'AVG_oCC_EX', 'StDev_oVC_EX']
    
    with sqlite3.connect(database) as conn:
        cur = conn.cursor()
        cur.execute(f"SELECT {', '.join(results_cols)} FROM {table}")
        results = cur.fetchall()
        results_data = pd.DataFrame(results, columns=results_cols)

    return results_data

def select_var(database: str, var: str, table: str = "ReachAttributes", where: str = None):
    """
    Helper function to return column of values for a specified feature from a specified table
    :param database: path to a BRAT database (.gpkg)
    :param var: database name of the feature to be returned"""
    with sqlite3.connect(database) as conn:
        curs = conn.cursor()
        stmt = f"SELECT {var} FROM {table}"
        if where is not None:
            stmt += f" WHERE {where}"
        curs.execute(stmt)
        result = curs.fetchall()
        var_data = [row[0] for row in result]   # convert to ints from tuples

    print("Obtained {} {} values from database...".format(len(var_data), var))
    return var_data



