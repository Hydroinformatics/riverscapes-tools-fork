def test_1_identical_inputs(n_sims=1000):
    """
    Test 1: Use IDENTICAL inputs for 30m and 100m
    If sensitivity differs, there's definitely a bug
    """
    print("TEST 1: Identical Inputs")
    print("=" * 40)
    
    # Generate identical base inputs
    np.random.seed(42)  # For reproducibility
    base_input = np.random.normal(2.2, 0.4, 1)  # Same for both
    
    
    results = []
    
    for sim in range(n_sims):
        # Generate identical scale factors
        scale_30m = np.random.normal(1.0, 0.25)
        scale_100m = np.random.normal(1.0, 0.25)
        # scale_30m = 1.0
        # scale_100m = 1.0
        
        # Truncate to reasonable bounds
        scale_30m = np.clip(scale_30m, 0.5, 1.5)
        scale_100m = np.clip(scale_100m, 0.5, 1.5)
        
        feature_values = {
            1: {
                'iVeg_30EX': base_input,
                'iVeg100EX': base_input,
                'oVC': None # Placeholder, will be filled by Veg FIS
            }
        }
        
        # Simulate FIS with identical inputs but different scales
        calculate_vegetation_fis_custom(feature_values, 'iVeg_30EX', 'iVeg100EX', 'oVC',
                                        'scale', scale_30m,
                                        'scale', scale_100m)
        
        results.append({
            'sim': sim,
            '30m_scale': scale_30m,
            '100m_scale': scale_100m,
            'oVC': feature_values[1]['oVC']
        })
    
    test_data = pd.DataFrame(results)
    print(test_data)
    
    # Calculate sensitivities
    corr_30m = stats.pearsonr(test_data['30m_scale'], test_data['oVC'])[0]
    corr_100m = stats.pearsonr(test_data['100m_scale'], test_data['oVC'])[0]
    
    print(f"30m scale sensitivity: {corr_30m:.4f}")
    print(f"100m scale sensitivity: {corr_100m:.4f}")
    print(f"Ratio (100m/30m): {corr_100m/corr_30m:.4f}")
    
    if abs(corr_30m - corr_100m) > 0.05:
        print("⚠️  WARNING: Asymmetric sensitivity with identical inputs!")
        print("   This suggests a bug in the FIS implementation")
    else:
        print("✅ PASS: Similar sensitivity with identical inputs")
    
    return test_data

