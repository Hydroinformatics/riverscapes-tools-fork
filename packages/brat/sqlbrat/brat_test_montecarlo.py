def test_4_extreme_scales():
    """
    Test 4: Test with extreme scale factors to check for asymmetric behavior
    """
    print("\nTEST 4: Extreme Scale Factors")
    print("=" * 40)
    
    np.random.seed(45)
    test_input_30m = np.random.normal(2.234, 0.5708, 100)
    test_input_100m = np.random.normal(2.107, 0.3793, 100)
    
    extreme_scales = [0.5, 1.0, 1.5, 2.0]
    
    results = []
    
    for i, scale_30m in enumerate(extreme_scales):
        for scale_100m in extreme_scales:
            feature_values = {
                i+1: {
                    'iVeg_30EX': test_input_30m,
                    'iVeg100EX': test_input_100m,
                    'oVC': None # Placeholder, will be filled by Veg FIS
                }
            }
            # Simulate FIS with identical inputs but different scales
            calculate_vegetation_fis_custom(feature_values, 'iVeg_30EX', 'iVeg100EX', 'oVC',
                                            'scale', scale_30m,
                                            'scale', scale_100m)
            
            results.append({
                '30m_scale': scale_30m,
                '100m_scale': scale_100m,
                'mean_oVC': feature_values[i+1]['oVC'],
                'scenario': f"30m:{scale_30m}, 100m:{scale_100m}"
            })
    
    results_df = pd.DataFrame(results)
    
    # Create a pivot table to see the pattern
    pivot = results_df.pivot(index='30m_scale', columns='100m_scale', values='mean_oVC')
    
    print("Mean oVC by scale combination:")
    print(pivot.round(3))
    
    # Check if the pattern is symmetric
    print(f"\nSymmetry check:")
    for i, scale_a in enumerate(extreme_scales):
        for j, scale_b in enumerate(extreme_scales):
            if i < j:  # Only check upper triangle
                val_ab = pivot.loc[scale_a, scale_b]
                val_ba = pivot.loc[scale_b, scale_a]
                diff = abs(val_ab - val_ba)
                print(f"({scale_a},{scale_b}) vs ({scale_b},{scale_a}): {val_ab:.3f} vs {val_ba:.3f}, diff: {diff:.4f}")
    
    return results_df



